export function shiftOpsSyntaxFixPlugin() {
  return {
    name: 'staffboard-shift-ops-syntax-fix',
    enforce: 'pre',
    transform(code, id) {
      if (!id.endsWith('/src/App.jsx')) return null
      const startMarker = '  const handoffSlackText = () => {'
      const endMarker = '  const copyHandoffSlack = async () => {'
      const start = code.indexOf(startMarker)
      const end = start >= 0 ? code.indexOf(endMarker, start) : -1
      if (start < 0 || end < 0) return null

      const safeBlock = `  const handoffSlackText = () => {
    const day = scopedBoardSummaries.find((row) => row.boardId === activeBoardType + '_day')
    const night = scopedBoardSummaries.find((row) => row.boardId === activeBoardType + '_night')
    const remaining = Math.max(0, (day?.goal || 0) + (night?.goal || 0) - (day?.completed || 0) - (night?.completed || 0))
    return [
      activeBoardTypeLabel + ' Shift Handoff — Week of ' + state.weekStartDate + ' — ' + state.selectedDay,
      'Day: HC ' + (day?.headcount || 0) + ' | Completed ' + (day?.completed || 0).toFixed(0) + ' | Goal ' + (day?.goal || 0).toFixed(0) + ' | TPH ' + (day?.normalizedTPH || 0).toFixed(2),
      'Night: HC ' + (night?.headcount || 0) + ' | Completed ' + (night?.completed || 0).toFixed(0) + ' | Goal ' + (night?.goal || 0).toFixed(0) + ' | TPH ' + (night?.normalizedTPH || 0).toFixed(2),
      'Remaining weighted work: ' + remaining.toFixed(0),
      'Risks: ' + (activeRiskFlags.length ? activeRiskFlags.join('; ') : 'none'),
      'Notes: ' + (state.handoffNotes || 'none'),
      'Generated by ' + enhancementAdmin + ' at ' + new Date().toLocaleString(),
    ].join(String.fromCharCode(10))
  }

`
      const next = code.slice(0, start) + safeBlock + code.slice(end)
      return { code: next, map: null }
    },
  }
}
